#!/usr/bin/env python3
"""Generate the lowercase table of ``util::locale::to_lower``.

The table holds every code point whose lowercase is one other code point, from
the Unicode data of the Python that runs this script, baked into committed C++
(``lowercase_table.cpp``). The build only compiles the output; there is no
build-time dependency on this script. Re-run it with a newer Python to take a
newer version of Unicode:

    python3 tools/util/generate_lowercase.py

``str.lower`` gives the full lowercase. The only letter whose full lowercase is
more than one code point is U+0130, which becomes ``i`` and a combining dot;
the table takes its simple lowercase, ``i``, as UnicodeData.txt states it.
"""

from __future__ import annotations

import os
import unicodedata

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(os.path.dirname(_HERE))
_OUTPUT = os.path.join(_ROOT, "src", "odr", "internal", "util", "lowercase_table.cpp")

# The simple lowercase of the letters whose full lowercase is longer.
_SIMPLE = {0x0130: 0x0069}


def _pairs() -> list[tuple[int, int]]:
    pairs = []
    for code in range(0x110000):
        lower = chr(code).lower()
        if len(lower) == 1 and ord(lower) != code:
            pairs.append((code, ord(lower)))
        elif len(lower) > 1:
            if code not in _SIMPLE:
                raise SystemExit(f"U+{code:04X} has no simple lowercase here")
            pairs.append((code, _SIMPLE[code]))
    return pairs


def main() -> None:
    pairs = _pairs()
    lines = [
        "// Generated by tools/util/generate_lowercase.py from Unicode "
        f"{unicodedata.unidata_version}.",
        "// Do not edit.",
        "",
        "#include <odr/internal/util/lowercase_table.hpp>",
        "",
        "#include <array>",
        "",
        "namespace odr::internal {",
        "",
        "std::span<const util::locale::LowercasePair>",
        "util::locale::lowercase_pairs() {",
        f"  static constexpr std::array<LowercasePair, {len(pairs)}> pairs{{{{",
    ]
    for letter, lower in pairs:
        lines.append(f"      {{0x{letter:04X}, 0x{lower:04X}}},")
    lines += ["  }};", "  return pairs;", "}", "", "} // namespace odr::internal", ""]
    with open(_OUTPUT, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))
    print(f"{len(pairs)} pairs -> {_OUTPUT}")


if __name__ == "__main__":
    main()
