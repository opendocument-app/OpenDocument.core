#!/usr/bin/env python3
"""Generate the localized function names of the formula module.

A user of a German LibreOffice types ``=SUMME(A1;B1)``, and a file states
``SUM``. The page turns one into the other with a table of the names
LibreOffice shows in each language, baked here into committed C++
(``formula_function_names.cpp``). The build only compiles the output; there is
no build-time dependency on this script. Re-run it whenever the pin, the
languages or the functions of the evaluator change:

    python3 tools/formula/generate_function_names.py

Source data -- ``source/<language>/formula/messages.po`` of the LibreOffice
translations (MPL-2.0) -- is fetched from a pinned commit into the git-ignored
``po/`` cache next to this script and reused on later runs. See
``tools/formula/THIRD_PARTY_LICENSES.md``.

A function name is an entry of the context ``RID_STRLIST_FUNCTION_NAMES``: its
``msgid`` is the English name, its ``msgstr`` the translation, empty where the
language keeps the English one. Only the functions the evaluator implements
(``FunctionEntry{"NAME", ...}`` in ``src/odr/internal/formula``) are kept.
"""

from __future__ import annotations

import glob
import os
import re
import urllib.request

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(os.path.dirname(_HERE))
_CACHE = os.path.join(_HERE, "po")
_OUTPUT = os.path.join(
    _ROOT, "src", "odr", "internal", "formula", "formula_function_names.cpp"
)

# Pinned commit of https://github.com/LibreOffice/translations
_COMMIT = "681a7f1e79cd6e27496259dab7940c8e490059de"

# The languages of `number_format::boolean_words`, as LibreOffice names them.
_LANGUAGES = [
    "cs", "da", "de", "es", "fi", "fr", "hu", "it", "nb", "nl", "pl", "pt",
    "pt-BR", "ru", "sv", "tr",
]


def _po(language: str) -> str:
    path = os.path.join(_CACHE, language + ".po")
    if not os.path.exists(path):
        os.makedirs(_CACHE, exist_ok=True)
        url = (
            "https://raw.githubusercontent.com/LibreOffice/translations/"
            f"{_COMMIT}/source/{language}/formula/messages.po"
        )
        with urllib.request.urlopen(url) as response:
            data = response.read()
        with open(path, "wb") as file:
            file.write(data)
    with open(path, encoding="utf-8") as file:
        return file.read()


def _unquote(text: str) -> str:
    return "".join(
        part.encode("latin-1", "backslashreplace").decode("unicode_escape")
        if "\\" in part
        else part
        for part in re.findall(r'"((?:[^"\\]|\\.)*)"', text)
    )


def _function_names(po: str) -> dict[str, str]:
    result = {}
    for block in po.split("\n\n"):
        if 'msgctxt "RID_STRLIST_FUNCTION_NAMES"' not in block:
            continue
        msgid = re.search(r"^msgid (.*?)(?=^msgstr )", block, re.S | re.M)
        msgstr = re.search(r"^msgstr (.*)", block, re.S | re.M)
        if msgid is None or msgstr is None:
            continue
        english = _unquote(msgid.group(1))
        localized = _unquote(msgstr.group(1))
        if localized and localized != english:
            result[english] = localized
    return result


def _implemented() -> set[str]:
    names = set()
    for path in glob.glob(
        os.path.join(_ROOT, "src", "odr", "internal", "formula", "*.cpp")
    ):
        with open(path, encoding="utf-8") as file:
            names.update(re.findall(r'FunctionEntry\{"([A-Z0-9.]+)"', file.read()))
    return names


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    implemented = _implemented()
    rows = []
    for language in _LANGUAGES:
        names = _function_names(_po(language))
        for english in sorted(names):
            if english in implemented:
                rows.append((language, english, names[english]))
    lines = [
        "// Generated by tools/formula/generate_function_names.py from the",
        "// LibreOffice translations at",
        f"// {_COMMIT}. Do not edit.",
        "",
        "#include <odr/internal/formula/formula_function_names.hpp>",
        "",
        "#include <array>",
        "",
        "namespace odr::internal {",
        "",
        "std::span<const formula::FunctionName> formula::function_names() {",
        f"  static constexpr std::array<FunctionName, {len(rows)}> names{{{{",
    ]
    for language, english, localized in rows:
        lines.append(
            f'      {{"{language}", "{_escape(english)}", "{_escape(localized)}"}},'
        )
    lines += ["  }};", "  return names;", "}", ""]
    # Only the alphabet of these names is needed. Turkish pairs I with a
    # dotless and İ with a dotted lowercase letter, which `lower()` gets wrong.
    letters = sorted(set("".join(localized for _, _, localized in rows)))
    lines += [
        "char32_t formula::lower_function_letter(const char32_t letter,",
        "                                        const std::string_view language) {",
        '  if (language == "tr" && letter == U\'I\') {',
        "    return U'ı';",
        "  }",
        '  if (language == "tr" && letter == U\'İ\') {',
        "    return U'i';",
        "  }",
        "  switch (letter) {",
    ]
    for letter in letters:
        lower = letter.lower()
        if lower != letter and len(lower) == 1:
            lines += [f"  case U'{letter}':", f"    return U'{lower}';"]
    lines += [
        "  default:", "    return letter;", "  }", "}", "",
        "} // namespace odr::internal", "",
    ]
    with open(_OUTPUT, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))
    print(f"{len(rows)} names in {len(_LANGUAGES)} languages -> {_OUTPUT}")


if __name__ == "__main__":
    main()
